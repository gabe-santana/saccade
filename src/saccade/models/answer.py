"""The result of :meth:`saccade.Video.ask`."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any, Literal

from saccade.models.context import Evidence
from saccade.models.frame import Frame


@dataclass(frozen=True, slots=True)
class Answer:
    """An LLM's answer plus exactly what it was shown.

    ``text`` is generated by your LLM. ``evidence`` and ``frames`` are the source material
    Saccade sent with the question — timestamps there come from the video, not the LLM.

    Attributes:
        question: What was asked.
        text: The LLM's answer.
        evidence: Transcript segments and frames that were sent, with source timestamps.
        frames: The images that were sent.
        mode: ``"full"`` (whole transcript sent) or ``"retrieved"`` (relevant passages only).
        model: Model name reported by the endpoint.
        usage: Token usage reported by the endpoint (summed over all exploration steps).
        steps: What the model did while exploring, e.g. ``"Zooming into 6:15"``.
    """

    question: str
    text: str
    evidence: list[Evidence]
    frames: list[Frame]
    mode: Literal["full", "retrieved"]
    model: str | None = None
    usage: dict[str, Any] = field(default_factory=dict)
    steps: list[str] = field(default_factory=list)

    @property
    def input_tokens(self) -> int | None:
        """Prompt tokens billed by the endpoint (transcript, images, instructions)."""
        return _usage(self.usage, "prompt_tokens", "input_tokens")

    @property
    def output_tokens(self) -> int | None:
        """Completion tokens billed by the endpoint, including hidden reasoning."""
        return _usage(self.usage, "completion_tokens", "output_tokens")

    @property
    def cached_tokens(self) -> int:
        """Input tokens served from the provider's prompt cache (billed at a large discount)."""
        details = (
            self.usage.get("prompt_tokens_details") or self.usage.get("input_tokens_details") or {}
        )
        value = details.get("cached_tokens") if isinstance(details, dict) else None
        return value if isinstance(value, int) else 0

    @property
    def reasoning_tokens(self) -> int:
        """Output tokens a reasoning model spent thinking (included in ``output_tokens``)."""
        details = (
            self.usage.get("completion_tokens_details")
            or self.usage.get("output_tokens_details")
            or {}
        )
        value = details.get("reasoning_tokens") if isinstance(details, dict) else None
        return value if isinstance(value, int) else 0

    @property
    def total_tokens(self) -> int | None:
        total = _usage(self.usage, "total_tokens")
        if total is None and self.input_tokens is not None and self.output_tokens is not None:
            return self.input_tokens + self.output_tokens
        return total

    def to_dict(self) -> dict[str, Any]:
        return {
            "question": self.question,
            "text": self.text,
            "mode": self.mode,
            "model": self.model,
            "usage": self.usage,
            "steps": self.steps,
            "evidence": [e.to_dict() for e in self.evidence],
            "frames": [f.to_dict() for f in self.frames],
        }

    def to_json(self, *, indent: int | None = 2) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=indent)

    def __str__(self) -> str:
        return self.text


def _usage(usage: dict[str, Any], *keys: str) -> int | None:
    for key in keys:
        value = usage.get(key)
        if isinstance(value, int):
            return value
    return None
